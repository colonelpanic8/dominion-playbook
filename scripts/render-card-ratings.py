"""Render Card Glicko CSV exports as data/card-ratings.jsonl.

Usage: render-card-ratings.py <csv-dir> <fetched-date>
"""

import csv
import json
import sys
from pathlib import Path

SHEET = "https://docs.google.com/spreadsheets/d/1CaVOd1pgAgmjJHXPM1tVMVnlJOLDZaq8BxjW4I1NI1E"

TABLES = [
    ("cards", "kingdom"),
    ("events-projects", "event-project"),
    ("ways", "way"),
    ("landmarks", "landmark"),
    ("traits", "trait"),
    ("prophecies", "prophecy"),
    ("allies", "ally"),
]


def read(path):
    with open(path, newline="") as f:
        rows = list(csv.reader(f))
    header = rows[0]
    updated = header[-1].strip() if header[-2].startswith("Last Update") else ""
    entries = []
    for row in rows[1:]:
        if len(row) < 10 or not row[1].strip():
            continue
        entries.append((row[1].strip(), float(row[2]), row[9].strip() == "deprecated"))
    entries.sort(key=lambda e: -e[1])
    return updated, entries


def main():
    src, fetched = Path(sys.argv[1]), sys.argv[2]
    data = {name: read(src / f"{name}.csv") for name, _ in TABLES}
    updated = data["cards"][0]

    out = [
        json.dumps({"meta": {
            "source": SHEET,
            "fetched": fetched,
            "sheet_updated": updated,
            "note": "Generated by `just refresh-power`; don't edit by hand. "
                    "Query with data/card-ratings.py; see context/card-power.md.",
        }})
    ]
    for name, kind in TABLES:
        entries = data[name][1]
        for edition, group in (("current", [e for e in entries if not e[2]]), ("first", [e for e in entries if e[2]])):
            for i, (card, rating, _) in enumerate(group, 1):
                out.append(json.dumps({
                    "name": card, "rating": round(rating, 1), "rank": i,
                    "of": len(group), "kind": kind, "edition": edition,
                }, ensure_ascii=False))
    print("\n".join(out))


if __name__ == "__main__":
    main()
